class Command(BaseCommand):
    help = "Seed blog_posts table from frontend static blog content."

    def add_arguments(self, parser):
        parser.add_argument("--dry-run", action="store_true", help="Preview changes without writing to DB")
        parser.add_argument("--clear", action="store_true", help="Delete all existing blog posts first")

    def handle(self, *args, **options):
        dry_run = options["dry_run"]
        clear_first = options["clear"]

        if dry_run:
            self.stdout.write(self.style.WARNING("DRY RUN — no changes will be written."))

        # Clear if requested
        if clear_first:
            count = BlogPost.objects.count()
            if dry_run:
                self.stdout.write(f"Would delete {count} existing posts.")
            else:
                BlogPost.objects.all().delete()
                self.stdout.write(self.style.WARNING(f"Deleted {count} existing posts."))

        created = 0
        updated = 0
        skipped = 0

        for post_data in BLOG_POSTS:
            slug = post_data["slug"]

            # Build update_fields from the data
            update_fields = [f for f in post_data if f != "slug"]

            if dry_run:
                existing = BlogPost.objects.filter(slug=slug).exists()
                if existing:
                    self.stdout.write(f"  [DRY-RUN] Would update: {slug}")
                    updated += 1
                else:
                    self.stdout.write(f"  [DRY-RUN] Would create: {slug}")
                    created += 1
            else:
                obj, was_created = BlogPost.objects.update_or_create(
                    slug=slug,
                    defaults=post_data,
                )
                if was_created:
                    created += 1
                else:
                    updated += 1

        if not dry_run:
            self.stdout.write(self.style.SUCCESS(
                f"\nDone. Created: {created}, Updated: {updated}, Skipped: {skipped}"
            ))
        else:
            self.stdout.write(self.style.SUCCESS(
                f"\nDry-run summary. Would create: {created}, Would update: {updated}"
            ))
